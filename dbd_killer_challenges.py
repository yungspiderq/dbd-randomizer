def build_killer_power_challenges(killers):
    """Attach canonical power labels and omit unsupported/future characters."""
    rows = []
    for killer, trials in KILLER_POWER_TRIALS.items():
        if killer not in killers:
            continue
        power = killers[killer].get("power", "")
        for i, (title, rule) in enumerate(trials):
            rows.append({
                "ru": title,
                "side": "KILLER",
                "diff": 1 if i == 0 else 3,
                "kind": "power",
                "killer": killer,
                "power": power,
                "why": ("Практика способности выбранного убийцы." if i == 0
                        else "Усложнённое испытание на владение силой."),
                "text": rule,
            })
    return rows
